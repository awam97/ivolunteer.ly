<p><strong>المادة (1): التعريفات</strong><br>
المنصة: يقصد بها "أنا متطوع"، وهي منصة إلكترونية تابعة لمنظمة شباب العمل التطوعي، تهدف لتنظيم وتنسيق العمل التطوعي بين المتطوعين والمنظمات.<br>
المنظمة المالكة: منظمة شباب العمل التطوعي.<br>
المنظمات المشاركة: هي الجهات غير الربحية التي تقوم بإدراج فرص تطوعية عبر المنصة.<br>
المتطوع: هو أي شخص قام بالتسجيل في المنصة للمشاركة في الأعمال التطوعية دون الانتماء الرسمي لأي جهة.<br>
الفرص التطوعية: هي الأنشطة أو المبادرات التي يتم إدراجها في المنصة من قبل المنظمات المشاركة.</p>

<p><strong>المادة (2): أهداف المنصة</strong><br>
1. تعزيز ثقافة العمل التطوعي في المجتمع.<br>
2. تسهيل الوصول إلى الفرص التطوعية.<br>
3. توفير بيئة إلكترونية آمنة ومنظمة للربط بين المتطوعين والمنظمات.</p>

<p><strong>المادة (3): حقوق المتطوعين</strong><br>
1. الحصول على معلومات واضحة ومفصلة حول أي فرصة تطوعية قبل المشاركة.<br>
2. الحصول على بيئة آمنة ومحترمة أثناء تنفيذ النشاط التطوعي.<br>
3. الحصول على شهادة مشاركة من المنصة بعدد ساعات التطوع بعد الانتهاء من النشاط .<br>
4. الحصول على شهادة مشاركة من الجهة المنظمة بعد الانتهاء من النشاط (في حال توفرها).<br>
5. الحق في الانسحاب من أي نشاط تطوعي مع إشعار مسبق، دون أن يترتب عليه التزام قانوني.<br>
6. حماية بياناته الشخصية وفقًا لسياسة الخصوصية الخاصة بالمنصة.</p>

<p><strong>المادة (4): واجبات المتطوعين</strong><br>
1. الالتزام بالمواعيد والتعليمات الخاصة بالفرص التطوعية.<br>
2. احترام القوانين والقيم الأخلاقية أثناء أداء المهام.<br>
3. الحفاظ على سرية المعلومات التي يطلع عليها خلال العمل التطوعي.<br>
4. الالتزام بعدم تمثيل أي جهة رسمية أو التحدث باسم المنظمات المشاركة دون تفويض.<br>
5. عدم استخدام المنصة لأغراض تجارية أو سياسية أو شخصية.</p>

<p><strong>المادة (5): حقوق منظمة شباب العمل التطوعي</strong><br>
1. الإشراف الكامل على المنصة وإدارتها.<br>
2. تعديل أو حذف أي محتوى مخالف دون إشعار مسبق.<br>
3. قبول أو رفض تسجيل المتطوعين والمنظمات المشاركة بناءً على معايير المنصة.<br>
4. توثيق المشاركات التطوعية لحفظ سجل مساهمات المستخدمين.</p>

<p><strong>المادة (6): واجبات منظمة شباب العمل التطوعي</strong><br>
1. تطوير وصيانة المنصة بشكل دوري.<br>
2. مراقبة جودة الفرص التطوعية المنشورة.<br>
3. حماية بيانات المستخدمين والجهات المشاركة.<br>
4. توفير آلية تواصل فعالة مع المستخدمين للرد على الشكاوى أو المقترحات.</p>

<p><strong>المادة (7): حقوق المنظمات المشاركة</strong><br>
1. استخدام المنصة مجانًا لنشر فرصها التطوعية.<br>
2. استلام قوائم المتطوعين المسجلين في أنشطتها.<br>
3. طلب سيرة ذاتية أو مقابلة بسيطة مع المتطوعين عند الحاجة.<br>
4. تقييم أداء المتطوعين بعد كل فعالية.</p>

<p><strong>المادة (8): واجبات المنظمات المشاركة</strong><br>
1. إدراج فرص حقيقية وغير ربحية ضمن المنصة.<br>
2. تحديد المهام والمتطلبات بشكل واضح قبل كل نشاط.<br>
3. احترام حقوق المتطوعين وعدم استغلالهم ماديًا أو معنويًا.<br>
4. الالتزام بتقديم تجربة آمنة ومنظمة للمتطوعين.<br>
5. إصدار شهادات مشاركة للمتطوعين عند انتهاء النشاط (عند الإمكان).</p>

<p><strong>المادة (9): الأحكام العامة</strong><br>
1. تعتبر هذه اللائحة ملزمة لجميع مستخدمي المنصة.<br>
2. يحق للمنصة تعديل اللائحة في أي وقت، على أن يتم إشعار المستخدمين بذلك.<br>
3. أي مخالفات جسيمة من أي طرف تمنح إدارة المنصة الحق في تعليق أو حظر الحساب.<br>
4. تسري هذه اللائحة من تاريخ نشرها على المنصة، وتظل سارية إلى حين استبدالها أو تعديلها.</p>
